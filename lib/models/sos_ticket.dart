import 'package:latlong2/latlong.dart';

enum TicketStatus {
  pending,
  accepted,
  enRoute,
  fulfilled,
  cancelled,
}

class SosTicket {
  final String id;
  final String patientName;
  final String bloodGroup;
  final int unitsRequired;
  int unitsFulfilled;
  final String hospitalName;
  final String hospitalAddress;
  final String hospitalPhone;
  final String triageNotes;
  final double latitude;
  final double longitude;
  final DateTime createdAt;
  double radiusKm;
  TicketStatus status;
  String? acceptedDonorName;
  String? acceptedDonorPhone;
  final String handoverOtp; // 4-digit code generated by hospital triage
  List<LatLng> routePoints; // Calculated road waypoints from donor to hospital
  int? etaMinutes;
  DateTime? acceptedAt;
  DateTime? fulfilledAt;

  SosTicket({
    required this.id,
    required this.patientName,
    required this.bloodGroup,
    required this.unitsRequired,
    this.unitsFulfilled = 0,
    required this.hospitalName,
    required this.hospitalAddress,
    this.hospitalPhone = '+91 11 2658 8500',
    this.triageNotes = 'Trauma / Surgery ICU Desk',
    required this.latitude,
    required this.longitude,
    required this.createdAt,
    this.radiusKm = 5.0,
    this.status = TicketStatus.pending,
    this.acceptedDonorName,
    this.acceptedDonorPhone,
    required this.handoverOtp,
    this.routePoints = const [],
    this.etaMinutes,
    this.acceptedAt,
    this.fulfilledAt,
  });

  bool get isLocked => unitsFulfilled >= unitsRequired || status == TicketStatus.fulfilled;

  SosTicket copyWith({
    String? id,
    String? patientName,
    String? bloodGroup,
    int? unitsRequired,
    int? unitsFulfilled,
    String? hospitalName,
    String? hospitalAddress,
    String? hospitalPhone,
    String? triageNotes,
    double? latitude,
    double? longitude,
    DateTime? createdAt,
    double? radiusKm,
    TicketStatus? status,
    String? acceptedDonorName,
    String? acceptedDonorPhone,
    String? handoverOtp,
    List<LatLng>? routePoints,
    int? etaMinutes,
    DateTime? acceptedAt,
    DateTime? fulfilledAt,
  }) {
    return SosTicket(
      id: id ?? this.id,
      patientName: patientName ?? this.patientName,
      bloodGroup: bloodGroup ?? this.bloodGroup,
      unitsRequired: unitsRequired ?? this.unitsRequired,
      unitsFulfilled: unitsFulfilled ?? this.unitsFulfilled,
      hospitalName: hospitalName ?? this.hospitalName,
      hospitalAddress: hospitalAddress ?? this.hospitalAddress,
      hospitalPhone: hospitalPhone ?? this.hospitalPhone,
      triageNotes: triageNotes ?? this.triageNotes,
      latitude: latitude ?? this.latitude,
      longitude: longitude ?? this.longitude,
      createdAt: createdAt ?? this.createdAt,
      radiusKm: radiusKm ?? this.radiusKm,
      status: status ?? this.status,
      acceptedDonorName: acceptedDonorName ?? this.acceptedDonorName,
      acceptedDonorPhone: acceptedDonorPhone ?? this.acceptedDonorPhone,
      handoverOtp: handoverOtp ?? this.handoverOtp,
      routePoints: routePoints ?? this.routePoints,
      etaMinutes: etaMinutes ?? this.etaMinutes,
      acceptedAt: acceptedAt ?? this.acceptedAt,
      fulfilledAt: fulfilledAt ?? this.fulfilledAt,
    );
  }

  Map<String, dynamic> toJson() => {
    'id': id,
    'patientName': patientName,
    'bloodGroup': bloodGroup,
    'unitsRequired': unitsRequired,
    'unitsFulfilled': unitsFulfilled,
    'hospitalName': hospitalName,
    'hospitalAddress': hospitalAddress,
    'hospitalPhone': hospitalPhone,
    'triageNotes': triageNotes,
    'latitude': latitude,
    'longitude': longitude,
    'createdAt': createdAt.toIso8601String(),
    'radiusKm': radiusKm,
    'status': status.name,
    'acceptedDonorName': acceptedDonorName,
    'acceptedDonorPhone': acceptedDonorPhone,
    'handoverOtp': handoverOtp,
    'etaMinutes': etaMinutes,
    'acceptedAt': acceptedAt?.toIso8601String(),
    'fulfilledAt': fulfilledAt?.toIso8601String(),
    'routePoints': routePoints.map((p) => {'lat': p.latitude, 'lng': p.longitude}).toList(),
  };

  factory SosTicket.fromJson(Map<String, dynamic> json) => SosTicket(
    id: json['id'] as String,
    patientName: json['patientName'] as String,
    bloodGroup: json['bloodGroup'] as String,
    unitsRequired: (json['unitsRequired'] as num).toInt(),
    unitsFulfilled: (json['unitsFulfilled'] as num?)?.toInt() ?? 0,
    hospitalName: json['hospitalName'] as String,
    hospitalAddress: json['hospitalAddress'] as String,
    hospitalPhone: (json['hospitalPhone'] as String?) ?? '+91 11 2658 8500',
    triageNotes: (json['triageNotes'] as String?) ?? 'Trauma / Surgery ICU Desk',
    latitude: (json['latitude'] as num).toDouble(),
    longitude: (json['longitude'] as num).toDouble(),
    createdAt: DateTime.parse(json['createdAt'] as String),
    radiusKm: (json['radiusKm'] as num?)?.toDouble() ?? 5.0,
    status: TicketStatus.values.firstWhere(
      (e) => e.name == json['status'],
      orElse: () => TicketStatus.pending,
    ),
    acceptedDonorName: json['acceptedDonorName'] as String?,
    acceptedDonorPhone: json['acceptedDonorPhone'] as String?,
    handoverOtp: (json['handoverOtp'] as String?) ?? '1234',
    etaMinutes: (json['etaMinutes'] as num?)?.toInt(),
    acceptedAt: json['acceptedAt'] != null ? DateTime.parse(json['acceptedAt'] as String) : null,
    fulfilledAt: json['fulfilledAt'] != null ? DateTime.parse(json['fulfilledAt'] as String) : null,
    routePoints: (json['routePoints'] as List<dynamic>?)
            ?.map((e) => LatLng(
                  (e['lat'] as num).toDouble(),
                  (e['lng'] as num).toDouble(),
                ))
            .toList() ??
        [],
  );
}
